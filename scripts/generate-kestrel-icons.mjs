import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = resolve(root, 'branding/kestrel-icon.json');
const source = JSON.parse(await readFile(sourcePath, 'utf8'));
const checkOnly = process.argv.includes('--check');
const unknownArguments = process.argv.slice(2).filter((argument) => argument !== '--check');

if (unknownArguments.length > 0) {
  throw new Error(`Unknown arguments: ${unknownArguments.join(', ')}`);
}

const outputs = new Map([
  ['web/app/icon.svg', renderWebIcon(source)],
  ['app/src/main/res/drawable/ic_launcher_background.xml', renderAndroidBackground(source)],
  ['app/src/main/res/drawable/ic_launcher_foreground.xml', renderAndroidMark(source, source.foregroundColor)],
  ['app/src/main/res/drawable/ic_launcher_monochrome.xml', renderAndroidMark(source, source.monochromeColor)],
]);

if (checkOnly) {
  const stalePaths = [];
  for (const [relativePath, expected] of outputs) {
    const actual = await readFile(resolve(root, relativePath), 'utf8').catch(() => null);
    if (actual !== expected) {
      stalePaths.push(relativePath);
    }
  }

  if (stalePaths.length > 0) {
    console.error(`Generated icon assets are stale:\n${stalePaths.map((path) => `- ${path}`).join('\n')}`);
    console.error('Run: just icons');
    process.exitCode = 1;
  } else {
    console.log('Generated icon assets are current.');
  }
} else {
  await Promise.all(
    [...outputs].map(async ([relativePath, content]) => {
      await writeFile(resolve(root, relativePath), content);
      console.log(`Generated ${relativePath}`);
    }),
  );
}

function renderWebIcon(icon) {
  const paths = icon.paths
    .map(
      (path) => `  <path
    fill="${icon.foregroundColor.toLowerCase()}"
    d="${path}"
  />`,
    )
    .join('\n');

  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${icon.canvasSize} ${icon.canvasSize}">
  <!-- Generated by scripts/generate-kestrel-icons.mjs. -->
  <title>Kestrel</title>
  <rect width="${icon.canvasSize}" height="${icon.canvasSize}" rx="${icon.webCornerRadius}" fill="${icon.backgroundColor.toLowerCase()}" />
${paths}
</svg>
`;
}

function renderAndroidBackground(icon) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-kestrel-icons.mjs. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${icon.canvasSize}dp"
    android:height="${icon.canvasSize}dp"
    android:viewportWidth="${icon.canvasSize}"
    android:viewportHeight="${icon.canvasSize}">
    <path
        android:fillColor="${icon.backgroundColor.toUpperCase()}"
        android:pathData="M0,0h${icon.canvasSize}v${icon.canvasSize}h-${icon.canvasSize}z" />
</vector>
`;
}

function renderAndroidMark(icon, color) {
  const paths = icon.paths
    .map(
      (path) => `    <path
        android:fillColor="${color.toUpperCase()}"
        android:pathData="${path}" />`,
    )
    .join('\n');

  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-kestrel-icons.mjs. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${icon.canvasSize}dp"
    android:height="${icon.canvasSize}dp"
    android:viewportWidth="${icon.canvasSize}"
    android:viewportHeight="${icon.canvasSize}">
${paths}
</vector>
`;
}
